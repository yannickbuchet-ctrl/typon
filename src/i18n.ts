const DICTIONNAIRES: Record<Langue, Record<Cle, Texte>> = { fr, en };

function detecter(): Langue {
  try {
    const v = localStorage.getItem(CLE_STOCKAGE);
    if (v === "fr" || v === "en") return v;
  } catch {
    /* stockage indisponible */
  }
  const nav = typeof navigator !== "undefined" ? navigator.language ?? "" : "";
  return nav.toLowerCase().startsWith("fr") ? "fr" : "en";
}

let courante: Langue = detecter();
/** Titre de la page en français, tel que l'écrit index.html (rétabli au retour au français). */
const titreInitial = typeof document !== "undefined" ? document.title : "";

export function langue(): Langue {
  return courante;
}

/** Locale des nombres et des dates. */
export function locale(): string {
  return courante === "fr" ? "fr-FR" : "en-US";
}

/** Met à jour <html lang> et le titre de la page. */
export function appliquerDocument() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = courante;
  document.title = courante === "fr" ? titreInitial : t("titre.application");
}

/** Change de langue et mémorise le choix. L'appelant redessine l'interface. */
export function choisirLangue(l: Langue) {
  courante = l;
  try {
    localStorage.setItem(CLE_STOCKAGE, l);
  } catch {
    /* stockage indisponible */
  }
  appliquerDocument();
}

function formaterParametre(v: string | number): string {
  if (typeof v !== "number") return v;
  if (!Number.isFinite(v)) return "—";
  return v.toLocaleString(locale(), { minimumFractionDigits: 0, maximumFractionDigits: Number.isInteger(v) ? 0 : 2 });
}

/**
 * Texte d'une clé dans la langue courante. `{nom}` est remplacé par le paramètre du même nom ; un paramètre `n`
 * choisit la forme du pluriel (français : 0 et 1 au singulier ; anglais : 1 seul au singulier).
 */
export function t(cle: Cle, params: Record<string, string | number> = {}): string {
  let texte = DICTIONNAIRES[courante][cle] ?? fr[cle];
  if (typeof texte !== "string") {
    const n = Number(params.n ?? 0);
    const singulier = courante === "fr" ? Math.abs(n) < 2 : Math.abs(n) === 1;
    texte = singulier ? texte.un : texte.plus;
  }
  return texte.replace(/\{(\w+)\}/g, (m, nom: string) => (nom in params ? formaterParametre(params[nom]) : m));
}
